def get_popular_cities():
    all_cities = []
    for c_info in COUNTRIES_CITIES.values():
        all_cities.extend(c_info["cities"][:6])
    return list(dict.fromkeys(all_cities))

def search_cities(query: str, limit: int = 15):
    q = query.lower().strip()
    if not q:
        return get_popular_cities()[:limit]
    results = []
    for c_info in COUNTRIES_CITIES.values():
        for city in c_info["cities"]:
            if q in city.lower():
                results.append(city)
                if len(results) >= limit:
                    return results
    return results
