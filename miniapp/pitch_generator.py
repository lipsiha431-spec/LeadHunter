"""
miniapp/pitch_generator.py — Генератор мульти-стилевых B2B офферов, ROI-калькулятора и демо-макетов.
С правилами естественной человеческой речи и глубокой персонализацией.
"""

from typing import Optional, Any
from miniapp.spheres_data import SPHERES


def find_sphere_by_id(sphere_id: str) -> Optional[dict]:
    for s in SPHERES:
        if s["id"] == sphere_id:
            return s
    return None


def generate_pitch(
    business_name: str,
    sphere_id: str,
    status_lead: str = "hot",
    freelancer_name: str = "",
    city: str = "",
    style: str = "hook"  # 'hook' (с крючка), 'expert' (экспертный), 'short' (короткий)
) -> str:
    """
    Генерирует живое, ненавязчивое первое сообщение в 3 стилях:
    - hook: факт о заведении первым предложением (видно в пуш-уведомлении)
    - expert: классическое вежливое представление с предложением макета
    - short: ультракороткий оффер для WhatsApp и SMS (2-3 предложения)
    """
    f_name = freelancer_name.strip()
    c_name = city.strip()
    b_name = business_name.strip() or "вашего заведения"
    sphere = find_sphere_by_id(sphere_id) or SPHERES[0]

    # --- СТИЛЬ 1: С КРЮЧКА (HOOK) — лучший Open Rate в Direct и TG ---
    if style == "hook":
        if status_lead == "hot":
            if sphere["id"] == "food":
                return (
                    f"Добрый день! Заметил, что у «{b_name}» на Google Картах нет сайта, и меню с телефона не посмотреть.\n\n"
                    f"Я{' ' + f_name if f_name else ''} собираю быстрые мобильные сайты-меню с заказом блюд{(' в ' + c_name) if c_name else ''}. "
                    f"Могу на днях бесплатно собрать рабочий макет на вашем меню: гость сможет легко выбрать блюдо, а сайт сам посоветует напиток или десерт к заказу.\n\n"
                    f"Собрать для вас такой наглядный черновик, чтобы вы посмотрели?"
                )
            elif sphere["id"] == "beauty":
                return (
                    f"Здравствуйте! У «{b_name}» на картах сейчас нет сайта, и клиентам сложно сразу с телефона увидеть работы мастеров и записаться.\n\n"
                    f"Я{' ' + f_name if f_name else ''} делаю аккуратные сайты с онлайн-записью для салонов красоты{(' в ' + c_name) if c_name else ''}. "
                    f"Предлагаю так: соберу макет под ваш стиль с услугами и ценами. Если понравится — обсудим детали, если нет — никаких обязательств.\n\n"
                    f"Сделать для вас такой макет?"
                )
            elif sphere["id"] == "auto":
                return (
                    f"Добрый день! Обратил внимание, что у «{b_name}» на картах не указан сайт с прайсом на работы.\n\n"
                    f"Водителям в дороге удобнее быстро открыть прайс и записаться без звонков. "
                    f"Я делаю сайты для автосервисов и детейлинга: есть готовый пример с калькулятором услуг.\n\n"
                    f"Скинуть ссылку глянуть с телефона?"
                )
            elif sphere["id"] == "lodging":
                return (
                    f"Здравствуйте! Увидел «{b_name}» на картах — красивое место, но нет сайта с прямым бронированием без комиссии сервисам (15-25%).\n\n"
                    f"Я{' ' + f_name if f_name else ''} делаю сайты с календарем свободных дат и моментальной бронью номеров. "
                    f"Есть рабочий пример такого сайта. Скинуть посмотреть, как это выглядит?"
                )
            else:
                return (
                    f"Добрый день! Заметил, что у «{b_name}» на картах пока нет сайта, и часть клиентов из поиска уходит к конкурентам.\n\n"
                    f"Я{' ' + f_name if f_name else ''} разрабатываю продающие сайты для заведений сферы «{sphere['name']}»{(' в ' + c_name) if c_name else ''}. "
                    f"Могу сделать черновик сайта под ваши услуги с ценами и заявкой.\n\n"
                    f"Интересно взглянуть на такой макет?"
                )
        else:
            return (
                f"Здравствуйте! У «{b_name}» на картах сейчас ссылка на шаблонный сервис. Страница рабочая, но там нет вашего брендинга и рекомендаций к заказу.\n\n"
                f"Я делаю собственные стильные сайты в едином стиле заведения. Могу собрать пример на ваших услугах, чтобы вы сравнили.\n\n"
                f"Показать, как это будет выглядеть?"
            )

    # --- СТИЛЬ 2: ЭКСПЕРТНЫЙ (EXPERT) ---
    elif style == "expert":
        name_intro = f"Меня зовут {f_name}, " if f_name else ""
        if status_lead == "hot":
            return (
                f"Здравствуйте! {name_intro}занимаюсь разработкой мобильных сайтов для бизнеса{(' в г. ' + c_name) if c_name else ''}.\n\n"
                f"Обратил внимание на карточку «{b_name}» в Google Картах: заведение имеет отличные отзывы, но собственный сайт отсутствует. "
                f"Из-за этого до 25% пользователей с карт, которые предпочитают заказывать или бронировать онлайн, отсеиваются.\n\n"
                f"Я могу подготовить рабочий концепт сайта под ваше заведение за свой счет. Вы посмотрите, как это работает, и только если понравится — поговорим о сотрудничестве.\n\n"
                f"Подготовить для вас такой макет?"
            )
        else:
            return (
                f"Добрый день! {name_intro}помогаю компаниям в сфере {sphere['name'].lower()} увеличивать конверсию из карт и соцсетей.\n\n"
                f"Заметил, что «{b_name}» использует внешний виджет. Обычно перевод клиентов на собственный сайт в фирменном стиле снижает отказы на 20-30% и увеличивает средний чек за счет умных допродаж.\n\n"
                f"Если вам актуально — с радостью покажу живые кейсы и набросаю концепт для вас. Что скажете?"
            )

    # --- СТИЛЬ 3: УЛЬТРАКОРОТКИЙ (SHORT) — для WhatsApp, SMS и Telegram ---
    else:
        if status_lead == "hot":
            return (
                f"Здравствуйте! Увидел «{b_name}» на картах без сайта. "
                f"Собрал аккуратный мобильный макет под ваши услуги с заказом с телефона. "
                f"Скинуть ссылку глянуть, как смотрится?"
            )
        else:
            return (
                f"Добрый день! Увидел «{b_name}» на картах — шаблонная ссылка не передает уровень заведения. "
                f"Есть наглядный пример собственного сайта в вашем стиле. Скинуть пример?"
            )


def calculate_business_roi(sphere_id: str, user_ratings_total: int = 50) -> dict[str, Any]:
    """
    Рассчитывает упущенную выгоду заведения из-за отсутствия сайта на картах.
    Используется как мощный аргумент в коммерческом предложении.
    """
    # Средние показатели по нишам (просмотры на картах в месяц на 1 отзыв, средний чек, потеря клиентов без сайта)
    sphere_metrics = {
        "food": {"views_multiplier": 18, "avg_check": 1200, "drop_rate": 0.18, "action": "заказать доставку или изучить меню"},
        "beauty": {"views_multiplier": 14, "avg_check": 2500, "drop_rate": 0.22, "action": "записаться к мастеру онлайн"},
        "auto": {"views_multiplier": 12, "avg_check": 4500, "drop_rate": 0.16, "action": "узнать прайс и записаться на ТО"},
        "health": {"views_multiplier": 15, "avg_check": 3500, "drop_rate": 0.20, "action": "посмотреть врачей и записаться"},
        "sport": {"views_multiplier": 12, "avg_check": 3000, "drop_rate": 0.19, "action": "купить пробное занятие"},
        "lodging": {"views_multiplier": 22, "avg_check": 8000, "drop_rate": 0.25, "action": "забронировать напрямую без комиссии"},
        "education": {"views_multiplier": 10, "avg_check": 4000, "drop_rate": 0.20, "action": "записаться на открытый урок"},
        "home": {"views_multiplier": 8, "avg_check": 15000, "drop_rate": 0.15, "action": "оставить заявку на замер"},
        "pets": {"views_multiplier": 12, "avg_check": 2000, "drop_rate": 0.18, "action": "записаться на прием"},
    }

    metrics = sphere_metrics.get(sphere_id, sphere_metrics["food"])
    ratings = max(user_ratings_total, 15)

    monthly_views = int(ratings * metrics["views_multiplier"])
    potential_leads = int(monthly_views * 0.05)  # 5% конверсия в интерес
    lost_clients = max(int(potential_leads * metrics["drop_rate"]), 5)
    lost_revenue = lost_clients * metrics["avg_check"]

    formatted_revenue = f"{lost_revenue:,}".replace(",", " ")
    avg_check_fmt = f"{metrics['avg_check']:,}".replace(",", " ")

    pitch_argument = (
        f"• Оценка упущенной выгоды:\n"
        f"При ~{monthly_views:,} просмотрах карточки в месяц отсутствие сайта отсекает от {lost_clients} клиентов, "
        f"которые предпочитают {metrics['action']} без звонков. "
        f"При среднем чеке {avg_check_fmt} ₽ потеря заведения составляет около {formatted_revenue} ₽ в месяц."
    ).replace(",", " ")

    return {
        "monthly_views": monthly_views,
        "lost_clients": lost_clients,
        "avg_check": metrics["avg_check"],
        "lost_revenue": lost_revenue,
        "formatted_revenue": formatted_revenue,
        "action": metrics["action"],
        "pitch_argument": pitch_argument,
    }


